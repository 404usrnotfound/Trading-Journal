  async function account(policy: 'fifo' | 'average' | 'specific' = 'fifo', base = usd) {
    const value = await catalog.createAccount(
      context,
      {
        name: `Fixture ${randomUUID()}`,
        environment: 'live',
        accountType: 'margin',
        baseCurrencyId: base,
        inventoryMethod: policy,
        allowShort: true,
        holdingMode: 'netted',
        effectiveAt: initial,
      },
      randomUUID(),
    );
    const bucket = await ledger.createCashBucket(context, {
      commandId: randomUUID(),
      accountId: value.id,
      currencyId: base,
      kind: 'settled',
    });
    return { id: value.id, bucket: bucket.id };
  }
  async function fill(
    scope: { id: string; bucket: string },
    side: 'buy' | 'sell',
    quantity: string,
    price: string,
    fee: string | null,
    day: number,
    extra: Partial<ExecutionInput> = {},
  ) {
    return ledger.recordExecution(context, {
      commandId: randomUUID(),
      accountId: scope.id,
      instrumentVersionId: instrument,
      side,
      quantity,
      price,
      cashBucketId: scope.bucket,
      economicAt: at(day),
      orderingKey: '1',
      costsComplete: true,
      ...(fee === null
        ? {}
        : {
            fees: [
              { cashBucketId: scope.bucket, currencyId: usd, amount: fee, kind: 'commission' },
            ],
          }),
      ...extra,
    });
  }
  async function cash(scope: { id: string }) {
    const values = await ledger.cashBalances(context, { accountIds: [scope.id] });
    return quantizeDecimal(
      values.reduce((total, value) => total.plus(value.amount), decimalValue('0')),
    );
  }
  async function book(scope: { id: string }, mark = '125') {
    const [position] = await ledger.positions(context, { accountId: scope.id });
    expect(position).toBeDefined();
    return {
      inventory: position!.inventory,
      valuation: valueInventory(position!.inventory, {
        mark: { id: 'fixture-mark', price: mark, multiplier: '1', instant: at(28) },
      }),
    };
  }

