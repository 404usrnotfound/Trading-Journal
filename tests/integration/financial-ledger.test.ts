    const cookie = login.headers
      .getSetCookie()
      .map((value) => value.split(';')[0])
      .join('; ');
    return services.authorizeWorkspace(
      new Request(`${origin}/api/workspaces`, { headers: { cookie } }),
      person.workspace.id,
      'editor',
    );
