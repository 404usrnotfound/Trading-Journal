import { createHash } from 'node:crypto';

/** Match env:init and Compose without permitting another daemon/host selector. */
export function recoveryComposeProjectName(value: string | undefined): string {
  const project = value ?? 'trading-journal-foundation';
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(project))
    throw new Error('COMPOSE_PROJECT_NAME must be a valid local Compose project name');
  return project;
}

/** Operational drills never accept a caller-selected existing database. */
export function assertOwnedRecoveryDatabase(name: string, generated: ReadonlySet<string>): void {
  if (!/^journal_(?:perf|recovery)_[0-9a-f]{32}_test$/.test(name) || !generated.has(name))
    throw new Error('The recovery drill can only use databases generated by this invocation');
}

export function recoveryDigest(value: string | Uint8Array): string {
  return createHash('sha256').update(value).digest('hex');
}

export type RecoveryRole = {
  rolname: string;
  rolcanlogin: boolean;
  rolinherit: boolean;
  rolsuper: boolean;
  rolcreatedb: boolean;
  rolcreaterole: boolean;
  rolbypassrls: boolean;
  rolreplication: boolean;
};

export function validateRecoveryRoles(
  roles: readonly RecoveryRole[],
  membershipCount: number,
): void {
  const expected = ['journal_app', 'journal_auth', 'journal_jobs', 'journal_migrator'];
  if (
    roles.length !== expected.length ||
    new Set(roles.map((role) => role.rolname)).size !== expected.length ||
    membershipCount !== 0 ||
    roles.some(
      (role) =>
        !expected.includes(role.rolname) ||
        role.rolinherit ||
        role.rolsuper ||
        role.rolcreatedb ||
        role.rolcreaterole ||
        role.rolreplication ||
        role.rolcanlogin !== (role.rolname !== 'journal_migrator') ||
        role.rolbypassrls !== (role.rolname === 'journal_migrator'),
    )
  )
    throw new Error('Recovery roles do not match the reviewed isolated privilege model');
}

/** Hash database-rendered JSON text; never parse decimal numbers through JS Number. */
export function compareRecoverySnapshots<T>(before: T, after: T): void {
  if (JSON.stringify(before) !== JSON.stringify(after))
    throw new Error('Recovery verification differs from the quiesced source snapshot');
}
